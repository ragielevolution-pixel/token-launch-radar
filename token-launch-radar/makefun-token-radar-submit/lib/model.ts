// Token Radar model "m2-peer": one sealed DefiLlama snapshot in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a
// ceiling) and adds the pre-token protocols below the watchlist floor that pass
// the watchlist's own rule (pre-token, not a bridge / liquid-staking /
// restaking / CEX product, name not versioned, no wrapped/staked word, not
// named after an exchange), by TVL. A protocol is pre-token when its snapshot
// entry records no token (no market cap, no CoinGecko id, no symbol). Live-token
// protocols are kept apart and shown as the market's own values, never mixed
// into the ranked board.
//
// Implied value follows only from the snapshot's own figures. No protocol name
// is ever special-cased: the same function scores every row.
//
//   peer multiple = median(mcap_usd / tvl_usd) over live-token protocols in
//                   the same category (at least 3 peers), else the global
//                   median over all live-token protocols; clamped to
//                   [0.10, 4.00]. A peer is a protocol with mcap_usd > 0 and
//                   tvl_usd > 0: a $0 market cap is not a trading value, and
//                   the snapshot holds 15 such protocols, all of which do
//                   record a token.
//   base          = tvl_usd x peer multiple
//   growth        = clamp(change_7d, -40, 80) per cent
//   growthMult    = 1 + (growth / 100) x 0.6
//   maturity      = 0.70 + min(age_days, 1460) / 1460 x 0.50
//                   (age_days unknown: 365)
//   chainMult     = 1 + min(chains - 1, 5) x 0.04
//   implied       = max(1, round(base x growthMult x maturity x chainMult))
//
// The constants are stated in the dashboard and changeable here. The implied
// value is this entry's own claim about what a launch would be worth if the
// protocol's record stayed as it is; it does not predict whether or when a
// token is issued.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

